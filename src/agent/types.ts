export interface ModelToolSpec {
  name: string;
  description: string;
  parameters: Record<string, unknown>;
}

export interface ModelToolCall {
  name: string;
  /** Raw arguments as produced by the model (object, JSON string, or garbage). */
  arguments: unknown;
}

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant' | 'tool';
  content: string;
  toolCalls?: ModelToolCall[];
  toolName?: string;
}

export interface ModelTurn {
  content: string;
  toolCalls: ModelToolCall[];
  /** How the tool calls were obtained: native tool calling, JSON adapter, or recovered from text. */
  mode: 'native' | 'json' | 'text';
  /** true when generation stopped at the reply-length cap (the text may end mid-sentence). */
  truncated?: boolean;
}

export type ModelErrorKind = 'unreachable' | 'model_missing' | 'timeout' | 'tools_unsupported' | 'bad_response';

export class ModelError extends Error {
  constructor(
    public readonly kind: ModelErrorKind,
    message: string,
  ) {
    super(message);
  }
}

export interface ModelAdapter {
  readonly label: string;
  chat(messages: ChatMessage[], tools: ModelToolSpec[], signal?: AbortSignal): Promise<ModelTurn>;
}

export type ActivityStatus = 'running' | 'success' | 'error' | 'skipped' | 'awaiting_confirmation';

export interface ActivityRecord {
  id: string;
  tool: string;
  purpose: string;
  status: ActivityStatus;
  origin: 'agent' | 'ui' | 'confirmation';
  startedAt: string;
  durationMs?: number;
  summary?: string;
}

export interface PendingActionView {
  id: string;
  toolName: string;
  summary: string;
  status: 'pending' | 'confirmed' | 'cancelled' | 'failed' | 'expired';
  preview?: unknown;
  resultSummary?: string | null;
  createdAt: string;
}

export interface MemoryContextItem {
  id: number;
  content: string;
  category: string;
  source: 'user' | 'inferred';
}

export type AgentEvent =
  | { type: 'run_started'; runId: string; conversationId: string; model: string }
  | { type: 'context'; memories: MemoryContextItem[]; relevance: 'matched' | 'recent' | 'none' }
  | { type: 'status'; message: string }
  | { type: 'activity'; activity: ActivityRecord }
  | { type: 'confirmation_required'; action: PendingActionView }
  | { type: 'final'; result: AgentResultView }
  | { type: 'error'; message: string };

export type AgentStatus = 'completed' | 'awaiting_confirmation' | 'limit_reached' | 'model_error' | 'mcp_error' | 'invalid_output' | 'cancelled';

export interface AgentResultView {
  message: string;
  status: AgentStatus;
  /** true when the text is composed by the application rather than generated by the model */
  systemComposed: boolean;
  notes: string[];
  iterations: number;
  toolCalls: number;
}
