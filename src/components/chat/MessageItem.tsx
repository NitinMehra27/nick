'use client';

import type { ActivityRecord, MemoryContextItem, PendingActionView } from '@/lib/client';
import { NickCore } from '../NickCore';
import { Badge, Spinner } from '../ui';
import { ActivityList } from './ActivityList';
import { PendingActionCard } from './PendingActionCard';

export interface UiMessage {
  key: string;
  role: 'user' | 'assistant';
  content: string;
  streaming?: boolean;
  statusText?: string;
  meta?: {
    status?: string;
    systemComposed?: boolean;
    notes?: string[];
    activity?: ActivityRecord[];
    pendingActionIds?: string[];
    memoryContext?: MemoryContextItem[];
    model?: string;
  };
}

const STATUS_LABEL: Record<string, { tone: 'warn' | 'bad'; label: string }> = {
  awaiting_confirmation: { tone: 'warn', label: 'Needs confirmation' },
  limit_reached: { tone: 'warn', label: 'Stopped at safety limit' },
  model_error: { tone: 'bad', label: 'Model unavailable' },
  mcp_error: { tone: 'bad', label: 'MCP server unavailable' },
  invalid_output: { tone: 'bad', label: 'Invalid model output' },
  cancelled: { tone: 'warn', label: 'Stopped by you' },
  failed: { tone: 'bad', label: 'Failed' },
};

export function MessageItem({
  message,
  pendingActions,
  onActionResolved,
}: {
  message: UiMessage;
  pendingActions: Record<string, PendingActionView>;
  onActionResolved: (a: PendingActionView, text: string) => void;
}) {
  if (message.role === 'user') {
    return (
      <div className="flex justify-end">
        <div className="max-w-[85%] whitespace-pre-wrap break-words rounded-2xl rounded-br-md border border-accent/20 bg-accent-strong/20 px-4 py-2.5 text-sm text-ink">{message.content}</div>
      </div>
    );
  }

  const meta = message.meta ?? {};
  const activity = meta.activity ?? [];
  const status = meta.status ? STATUS_LABEL[meta.status] : undefined;
  const actions = (meta.pendingActionIds ?? []).map((id) => pendingActions[id]).filter(Boolean);

  return (
    <div className="flex gap-3">
      <NickCore state={message.streaming ? 'thinking' : 'idle'} size={28} className="mt-0.5" />
      <div className="min-w-0 flex-1">
        <div className="mb-1 flex flex-wrap items-center gap-1.5">
          <span className="text-xs font-semibold">NICK</span>
          {!message.streaming &&
            (meta.systemComposed ? (
              <Badge title="Written by the application from real tool results, not generated by the AI model">System message</Badge>
            ) : meta.model ? (
              <Badge tone="accent" title={meta.model}>
                AI-generated · local model
              </Badge>
            ) : null)}
          {status && <Badge tone={status.tone}>{status.label}</Badge>}
        </div>

        {(meta.memoryContext?.length ?? 0) > 0 && (
          <details className="mb-2 text-xs text-muted">
            <summary className="cursor-pointer select-none text-faint hover:text-muted">
              Used {meta.memoryContext!.length} saved memor{meta.memoryContext!.length === 1 ? 'y' : 'ies'} as context
            </summary>
            <ul className="mt-1 space-y-0.5 pl-4">
              {meta.memoryContext!.map((m) => (
                <li key={m.id}>
                  <span className="text-faint">#{m.id} [{m.source === 'user' ? 'saved by you' : 'inferred'}]</span> {m.content}
                </li>
              ))}
            </ul>
          </details>
        )}

        {activity.length > 0 && (
          <div className="mb-2 rounded-lg border border-line bg-surface px-3 py-2">
            <ActivityList items={activity} />
          </div>
        )}

        {message.streaming && !message.content ? (
          <p className="flex items-center gap-2 text-sm text-muted">
            <Spinner label="Working" /> {message.statusText ?? 'Starting…'}
          </p>
        ) : (
          <div className="whitespace-pre-wrap break-words text-sm leading-relaxed text-ink">{message.content}</div>
        )}

        {meta.notes?.map((n) => (
          <p key={n} className="mt-2 rounded-md border border-warn/30 bg-warn/5 px-2 py-1 text-xs text-warn">
            {n}
          </p>
        ))}

        {actions.map((a) => (
          <PendingActionCard key={a.id} action={a} onResolved={onActionResolved} />
        ))}
      </div>
    </div>
  );
}
